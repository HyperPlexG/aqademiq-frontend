function loadApp() {
  const app = fs.readFileSync(APP_JSX, 'utf8');
  const grab = (re, what) => {
    const m = re.exec(app);
    if (!m) throw new Error('app.jsx: could not find ' + what);
    return vm.runInNewContext('(' + m[1] + ')');
  };
  return {
    prismMark: grab(/const PRISM_MARK = (\{[^}]*\});/, 'PRISM_MARK'),
    moodExpr: grab(/const MOOD_EXPR = (\[[^\]]*\]);/, 'MOOD_EXPR'),
  };
}

/* ───────────────────────── paths ───────────────────────── */

/** Normalise and verify one path; returns rounded absolute M/L/C/Z ops. */
function norm(d, where) {
  const n = pack.normalize(d);
  const err = pack.pathError(d, n);
  if (!(err <= TOLERANCE)) throw new Error(`${where}: normalisation error ${err} > ${TOLERANCE}`);
  return n.ops;
}

/**
 * Make every closing segment explicit (a lineTo the subpath's start before Z).
 *
 * A timer layer is trimmed along its length, and rect() closes the cube with a
 * real piece of its top edge. Whether a platform's trim counts the implicit
 * closing segment is not something to rely on, so it is spelled out.
 */
function explicitClose(ops) {
  const out = [];
  let start = null;
  let cur = null;
  for (const o of ops) {
    if (o[0] === 'M') { start = [o[1], o[2]]; cur = start; }
    if (o[0] === 'Z' && start && cur && (cur[0] !== start[0] || cur[1] !== start[1])) {
      out.push(['L', start[0], start[1]]);
    }
    if (o[0] === 'L') cur = [o[1], o[2]];
    if (o[0] === 'C') cur = [o[5], o[6]];
    out.push(o);
    if (o[0] === 'Z') cur = start;
  }
  return out;
}

const OPCODE = { M: 0, L: 1, C: 2, Z: 3 };
const flat = (ops) => ops.flatMap((o) => [OPCODE[o[0]], ...o.slice(1)]);
const num = (v) => String(Object.is(v, -0) ? 0 : v);
/** Ops as VectorDrawable pathData: `M12,3 L14.6,3 C16.84,3 17.96,3 18.82,3.44 Z`. */
const pathData = (ops) => ops.map((o) => {
  const pts = [];
  for (let i = 1; i < o.length; i += 2) pts.push(num(o[i]) + ',' + num(o[i + 1]));
  return o[0] + pts.join(' ');
}).join(' ');

/* ───────────────────────── glyphs ───────────────────────── */

function buildGlyphs(icons) {
  const out = [];
  for (const name of GLYPHS) {
    const ic = icons[name];
    if (!ic) throw new Error('aq-icons.js: no glyph ' + name);
    const layers = ic.layers.map((l) => {
      for (const k of Object.keys(l)) {
        if (!['id', 'd', 'role', 'paint', 'timer'].includes(k)) throw new Error(`${name}.${l.id}: unsupported layer key ${k}`);
      }
      // body/knock only matter in the fill variant; a cut needs a mask the
      // renderers here do not draw.
      if (l.role === 'cut') throw new Error(`${name}.${l.id}: cut layers are not supported natively`);
      let ops = norm(l.d, `${name}.${l.id}`);
      if (l.timer) ops = explicitClose(ops);
      return { id: l.id, ops, paint: !!l.paint, timer: !!l.timer };
    });
    out.push({ name, label: ic.label, layers });
  }
  return out;
}

/* ───────────────────────── colour art (adaColor, adaPose) ───────────────────────── */

const ART_ATTRS = new Set(['id', 'd', 'cx', 'cy', 'r', 'fill', 'fill-opacity', 'stroke', 'stroke-width', 'stroke-opacity', 'stroke-linecap', 'stroke-linejoin']);
const INHERITED = ['fill', 'fill-opacity', 'stroke', 'stroke-width', 'stroke-opacity', 'stroke-linecap', 'stroke-linejoin'];

/** The few SVG shapes the pack's colour art uses, flattened to painted layers. */
function parseArt(svg, where) {
  const vb = /viewBox="([^"]+)"/.exec(svg);
  if (!vb) throw new Error(where + ': no viewBox');
  const [x, y, w, h] = vb[1].trim().split(/\s+/).map(Number);
  const layers = [];
  const stack = [{ attrs: {}, group: null }];
  const re = /<(\/?)([a-zA-Z]+)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g;
  let m;
  while ((m = re.exec(svg))) {
    const [, close, tag, attrText, selfClose] = m;
    if (tag === 'svg') continue;
    if (close) {
      if (tag === 'g') stack.pop();
      continue;
    }
    const attrs = {};
    attrText.replace(/([\w:-]+)="([^"]*)"/g, (_, k, v) => { attrs[k] = v; });
    for (const k of Object.keys(attrs)) if (!ART_ATTRS.has(k)) throw new Error(`${where}: unsupported attribute ${k} on <${tag}>`);
    const parent = stack[stack.length - 1];
    const merged = {};
    for (const k of INHERITED) {
      if (attrs[k] != null) merged[k] = attrs[k];
      else if (parent.attrs[k] != null) merged[k] = parent.attrs[k];
    }
    if (tag === 'g') {
      if (!selfClose) stack.push({ attrs: merged, group: attrs.id || parent.group });
      continue;
    }
    let d;
    if (tag === 'path') d = attrs.d;
    else if (tag === 'circle') {
      const cx = +attrs.cx, cy = +attrs.cy, r = +attrs.r;
      d = `M${cx - r} ${cy}A${r} ${r} 0 1 0 ${cx + r} ${cy}A${r} ${r} 0 1 0 ${cx - r} ${cy}Z`;
    } else throw new Error(`${where}: unsupported element <${tag}>`);
    const id = attrs.id || parent.group || tag;
    const fill = merged.fill == null ? '#000000' : merged.fill; // SVG's default fill
    const stroke = merged.stroke == null ? 'none' : merged.stroke;
    layers.push({
      id,
      group: parent.group,
      ops: norm(d, `${where}.${id}`),
      fill: fill === 'none' ? null : hex(fill, where),
      fillOpacity: merged['fill-opacity'] == null ? 1 : +merged['fill-opacity'],
      stroke: stroke === 'none' ? null : hex(stroke, where),
      strokeWidth: merged['stroke-width'] == null ? 1 : +merged['stroke-width'],
      strokeOpacity: merged['stroke-opacity'] == null ? 1 : +merged['stroke-opacity'],
      roundCap: merged['stroke-linecap'] === 'round',
      roundJoin: merged['stroke-linejoin'] === 'round',
    });
  }
  return { box: [x, y, w, h], layers };
}

function hex(c, where) {
  const m = /^#([0-9a-fA-F]{6})$/.exec(c);
  if (!m) throw new Error(`${where}: unsupported colour ${c}`);
  return m[1].toUpperCase();
}

function buildArt(win, app) {
  const brand = parseArt(win.AQ.adaColor(), 'adaColor');
  // The week row (MoodWeekRow): mood idx wears tone idx, melts by (4 - idx) / 4,
  // takes MOOD_EXPR[idx], and has no bubbles.
  const moods = app.moodExpr.map((expr, idx) => {
    const art = parseArt(win.AQ.adaPose({ rating: idx, melt: (4 - idx) / 4, expr }), `adaPose(${idx})`);
    art.layers = art.layers.filter((l) => l.group !== 'bubbles');
    return art;
  });
  if (moods.length !== 5) throw new Error('MOOD_EXPR: expected five moods');
  return { brand, moods };
}

/* ───────────────────────── Swift ───────────────────────── */

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

function emitSwift(glyphs, art, app) {
  const paths = new Map(); // key -> name
  const pathName = (ops) => {
    const key = JSON.stringify(ops);
    if (!paths.has(key)) paths.set(key, { name: 'p' + paths.size, ops });
    return 'AqPathData.' + paths.get(key).name;
  };
  const L = [];
  L.push(BEGIN + ' — do not edit by hand.');
  L.push('// Source: prototypes/v11/aq-icons.js (AQ.ICONS, AQ.adaColor, AQ.adaPose) and');
  L.push('// prototypes/v11/app.jsx (PRISM_MARK, MOOD_EXPR). Path data is the pack\'s 0 = move,');
  L.push('// 1 = line, 2 = cubic, 3 = close op list, in each design box, as in aq_glyphs.g.dart.');
  L.push('');
  L.push('extension AqGlyph {');
  for (const g of glyphs) {
    L.push(`    /// \`${g.name}\`: ${g.label}.`);
    L.push(`    static let ${camel(g.name)} = AqGlyph(layers: [`);
    for (const l of g.layers) {
      const extra = (l.paint ? ', paint: true' : '') + (l.timer ? ', timer: true' : '');
      L.push(`        AqGlyphLayer(path: ${pathName(l.ops)}${extra}),`);
    }
    L.push('    ])');
    L.push('');
  }
  L.push('    /// A Prism mode\'s mark, by the mode\'s name (app.jsx PRISM_MARK).');
  L.push('    static let prismMarks: [String: AqGlyph] = [');
  for (const [mode, glyph] of Object.entries(app.prismMark)) {
    if (!GLYPHS.includes(glyph)) throw new Error(`PRISM_MARK: ${mode} -> ${glyph} is not in GLYPHS`);
    L.push(`        "${mode}": .${camel(glyph)},`);
  }
  L.push('    ]');
  L.push('}');
  L.push('');
  const artLayer = (l) => {
    const args = [`path: ${pathName(l.ops)}`];
    if (l.fill) args.push(`fill: 0x${l.fill}`);
    if (l.fill && l.fillOpacity !== 1) args.push(`fillOpacity: ${num(l.fillOpacity)}`);
    if (l.stroke) args.push(`stroke: 0x${l.stroke}`);
    if (l.stroke) args.push(`strokeWidth: ${num(l.strokeWidth)}`);
    if (l.stroke && l.strokeOpacity !== 1) args.push(`strokeOpacity: ${num(l.strokeOpacity)}`);
    if (l.stroke && l.roundCap) args.push('roundCap: true');
    if (l.stroke && l.roundJoin) args.push('roundJoin: true');
    return `AqArtLayer(${args.join(', ')}),`;
  };
  const artValue = (a, indent) => {
    const [x, y, w, h] = a.box;
    const out = [`AqArt(box: CGRect(x: ${num(x)}, y: ${num(y)}, width: ${num(w)}, height: ${num(h)}), layers: [`];
    for (const l of a.layers) out.push(indent + '    ' + artLayer(l));
    out.push(indent + '])');
    return out;
  };
  L.push('extension AqArt {');
  L.push('    /// `aq_brand_ada`: Ada, full colour, in her fixed brand colours (AQ.adaColor).');
  const brand = artValue(art.brand, '    ');
  L.push('    static let brandAda = ' + brand[0]);
  L.push(...brand.slice(1));
  L.push('');
  L.push('    /// The week row\'s mood cubes, 0 Rough … 4 Great: AQ.adaPose with tone idx,');
  L.push('    /// melt (4 - idx) / 4 and MOOD_EXPR[idx], without bubbles (MoodWeekRow).');
  L.push('    static let moods: [AqArt] = [');
  for (const a of art.moods) {
    const v = artValue(a, '        ');
    L.push('        ' + v[0]);
    L.push(...v.slice(1, -1));
    L.push(v[v.length - 1] + ',');
  }
  L.push('    ]');
  L.push('}');
  L.push('');
  L.push('enum AqPathData {');
  for (const { name, ops } of paths.values()) {
    L.push(`    static let ${name}: [CGFloat] = [${flat(ops).map(num).join(', ')}]`);
  }
  L.push('}');
  L.push(END);
  return L;
}

function spliceSwift(lines) {
  const file = fs.readFileSync(SWIFT_FILE, 'utf8');
  const eol = file.includes('\r\n') ? '\r\n' : '\n';
  const begin = file.indexOf(BEGIN);
  const end = file.indexOf(END);
  if (begin < 0 || end < begin) throw new Error(`${path.relative(ROOT, SWIFT_FILE)}: GENERATED markers missing`);
  const tail = file.indexOf(eol, end);
  const after = tail < 0 ? '' : file.slice(tail);
  return file.slice(0, begin) + lines.join(eol) + after;
}

