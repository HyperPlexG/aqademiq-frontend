#!/usr/bin/env node
/*
 * The icon pack, for the surfaces Flutter cannot draw.
 *
 *   node tool/generate_ambient_glyphs.js           generate + verify
 *   node tool/generate_ambient_glyphs.js --check   verify only, write nothing
 *
 * The lock screen, the Dynamic Island, StandBy, the home-screen widgets, the watch
 * and the Android session card are drawn natively (WidgetKit, watchOS, RemoteViews),
 * so the v11 pack has to exist there a second time. It is not redrawn: this reads
 * the same source the Dart is generated from and emits it for each platform.
 *
 * Source of truth (never edit the output by hand):
 *   prototypes/v11/aq-icons.js   window.AQ.ICONS (glyphs), AQ.adaColor (aq_brand_ada),
 *                                AQ.adaPose (Ada's mood poses)
 *   prototypes/v11/app.jsx       PRISM_MARK (a Prism mode's glyph), MOOD_EXPR
 *
 * Output:
 *   ios/AmbientWidgets/AdaShape.swift   the block between the GENERATED markers: path
 *                                       data, AqGlyph and AqArt constants. That file,
 *                                       not a new one, because it is the one source both
 *                                       the widget extension and the watch compile; a
 *                                       new file would need ios/add_widget_target.rb and
 *                                       ios/add_watch_target.rb re-run before it built.
 *   android/.../res/drawable/
 *     ambient_cube_00..20.xml           aq_cube_session trimmed to 0/20..20/20 of time
 *                                       left, over aq_cube_frozen at 26%, in
 *                                       @color/ambient_ice (light / night twins)
 *     ambient_cube.xml                  the level-list over them (setImageLevel 0..20)
 *     aq_brand_ada.xml                  Ada, full colour (fixed brand colours)
 *     aq_ada_mood_0..4.xml              the week row's mood cubes, 0 Rough … 4 Great
 *   assets/images/notif_session_done.png
 *                                       Ada's session_done pose (AQ.POSES), the
 *                                       thumbnail the iOS "Session done" notification
 *                                       attaches (notif-ios). A notification can only
 *                                       attach a file, so this one is rasterised here,
 *                                       once, by a small scanline renderer below.
 *
 * Ada's melt-stage drawables, her status-bar masks and the Quick Settings tile icon
 * are not here: they come out of tool/generate_ada_android.py.
 *
 * Paths go through the same normaliser and checker as tool/generate_aq_icons.js
 * (absolute M/L/C/Z, verified against the original curves). Node built-ins only.
 */
