const XML_HEAD = '<?xml version="1.0" encoding="utf-8"?>';
const GEN_NOTE = 'GENERATED by tool/generate_ambient_glyphs.js — do not edit by hand.';

function strokeAttrs(color, width, alpha, extra) {
  return `android:strokeColor="${color}" android:strokeWidth="${num(width)}"` +
    (alpha !== 1 ? ` android:strokeAlpha="${num(alpha)}"` : '') +
    ' android:strokeLineCap="round" android:strokeLineJoin="round"' + (extra || '');
}

function cubeDrawable(glyphs, level) {
  const session = glyphs.find((g) => g.name === 'cube_session');
  const frozen = glyphs.find((g) => g.name === 'cube_frozen');
  const timer = session.layers.find((l) => l.timer);
  const glint = session.layers.find((l) => !l.timer);
  const track = frozen.layers.find((l) => l.id === 'cube');
  if (!timer || !glint || !track) throw new Error('cube_session/cube_frozen: unexpected layers');
  const left = level / CUBE_LEVELS;
  const ice = '@color/ambient_ice';
  const out = [
    XML_HEAD,
    `<!-- ${GEN_NOTE}`,
    `     aq_cube_session with ${Math.round(left * 100)}% of the session left, over aq_cube_frozen`,
    `     at ${Math.round(TRACK_ALPHA * 100)}%: the cube is the timer. Level ${level} of ambient_cube.xml. -->`,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    '    android:width="44dp"',
    '    android:height="44dp"',
    '    android:viewportWidth="24"',
    '    android:viewportHeight="24">',
    `    <path ${strokeAttrs(ice, STROKE, TRACK_ALPHA)}`,
    `        android:pathData="${pathData(track.ops)}" />`,
  ];
  if (level > 0) {
    const trim = level < CUBE_LEVELS ? ` android:trimPathEnd="${num(left)}"` : '';
    out.push(`    <path ${strokeAttrs(ice, STROKE, 1, trim)}`);
    out.push(`        android:pathData="${pathData(timer.ops)}" />`);
  }
  out.push(`    <path ${strokeAttrs(ice, STROKE, 1)}`);
  out.push(`        android:pathData="${pathData(glint.ops)}" />`);
  out.push('</vector>');
  return out;
}

function cubeLevelList() {
  const out = [
    XML_HEAD,
    `<!-- ${GEN_NOTE}`,
    '     The session cube by time left: setImageLevel(round(left * ' + CUBE_LEVELS + ')).',
    '     A notification or a widget cannot trim a path at runtime, so the trims are',
    '     drawn ahead of time and the level picks one. -->',
    '<level-list xmlns:android="http://schemas.android.com/apk/res/android">',
  ];
  for (let k = 0; k <= CUBE_LEVELS; k++) {
    out.push(`    <item android:maxLevel="${k}" android:drawable="@drawable/ambient_cube_${String(k).padStart(2, '0')}" />`);
  }
  out.push('</level-list>');
  return out;
}

function artDrawable(a, sizeDp, what) {
  const [x, y, w, h] = a.box;
  const out = [
    XML_HEAD,
    `<!-- ${GEN_NOTE}`,
    `     ${what} -->`,
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    `    android:width="${sizeDp}dp"`,
    `    android:height="${sizeDp}dp"`,
    `    android:viewportWidth="${num(w)}"`,
    `    android:viewportHeight="${num(h)}">`,
    `    <group android:translateX="${num(-x)}" android:translateY="${num(-y)}">`,
  ];
  for (const l of a.layers) {
    const attrs = [];
    if (l.fill) {
      attrs.push(`android:fillColor="#${l.fill}"`);
      if (l.fillOpacity !== 1) attrs.push(`android:fillAlpha="${num(l.fillOpacity)}"`);
    }
    if (l.stroke) {
      attrs.push(`android:strokeColor="#${l.stroke}"`, `android:strokeWidth="${num(l.strokeWidth)}"`);
      if (l.strokeOpacity !== 1) attrs.push(`android:strokeAlpha="${num(l.strokeOpacity)}"`);
      if (l.roundCap) attrs.push('android:strokeLineCap="round"');
      if (l.roundJoin) attrs.push('android:strokeLineJoin="round"');
    }
    out.push(`        <!-- ${l.id} -->`);
    out.push(`        <path ${attrs.join(' ')}`);
    out.push(`            android:pathData="${pathData(l.ops)}" />`);
  }
  out.push('    </group>');
  out.push('</vector>');
  return out;
}

function androidFiles(glyphs, art) {
  const files = {};
  for (let k = 0; k <= CUBE_LEVELS; k++) {
    files[`ambient_cube_${String(k).padStart(2, '0')}.xml`] = cubeDrawable(glyphs, k);
  }
  files['ambient_cube.xml'] = cubeLevelList();
  files['aq_brand_ada.xml'] = artDrawable(art.brand, 54, 'aq_brand_ada: Ada, full colour, in her fixed brand colours (AQ.adaColor).');
  const names = ['Rough', 'Tired', 'OK', 'Good', 'Great'];
  art.moods.forEach((a, i) => {
    files[`aq_ada_mood_${i}.xml`] = artDrawable(a, 30, `Ada, mood ${i} (${names[i]}), as the This week row draws her: AQ.adaPose, no bubbles.`);
  });
  return files;
}

/* ───────────────────────── PNG (the notification thumbnail) ───────────────────────── */

/** Each subpath as a polyline in grid units, and whether it closed. */
function polylines(ops, map) {
  const out = [];
  let cur = null;
  let pts = null;
  for (const o of ops) {
    if (o[0] === 'M') {
      if (pts) out.push({ pts, closed: false });
      cur = [o[1], o[2]];
      pts = [map(cur)];
    } else if (o[0] === 'L') {
      cur = [o[1], o[2]];
      pts.push(map(cur));
    } else if (o[0] === 'C') {
      const [x0, y0] = cur;
      for (let k = 1; k <= 24; k++) {
        const u = k / 24, v = 1 - u;
        const x = v * v * v * x0 + 3 * v * v * u * o[1] + 3 * v * u * u * o[3] + u * u * u * o[5];
        const y = v * v * v * y0 + 3 * v * v * u * o[2] + 3 * v * u * u * o[4] + u * u * u * o[6];
        pts.push(map([x, y]));
      }
      cur = [o[5], o[6]];
    } else if (o[0] === 'Z') {
      out.push({ pts, closed: true });
      pts = null;
    }
  }
  if (pts) out.push({ pts, closed: false });
  return out;
}

/** Non-zero fill of the polylines into a supersampled mask. */
function fillMask(lines, mask, g) {
  const edges = [];
  for (const { pts } of lines) {
    for (let i = 0; i < pts.length; i++) {
      const a = pts[i], b = pts[(i + 1) % pts.length];
      if (a[1] !== b[1]) edges.push(a, b);
    }
  }
  const xs = [];
  for (let row = 0; row < g; row++) {
    const y = row + 0.5;
    xs.length = 0;
    for (let e = 0; e < edges.length; e += 2) {
      const [x0, y0] = edges[e], [x1, y1] = edges[e + 1];
      if ((y >= y0 && y < y1) || (y >= y1 && y < y0)) {
        xs.push([x0 + (y - y0) * (x1 - x0) / (y1 - y0), y1 > y0 ? 1 : -1]);
      }
    }
    xs.sort((p, q) => p[0] - q[0]);
    let wind = 0;
    for (let i = 0; i < xs.length - 1; i++) {
      wind += xs[i][1];
      if (wind === 0) continue;
      const from = Math.max(0, Math.ceil(xs[i][0] - 0.5));
      const to = Math.min(g - 1, Math.floor(xs[i + 1][0] - 0.5));
      for (let col = from; col <= to; col++) mask[row * g + col] = 1;
    }
  }
}

/** A stroke as the union of its segments' neighbourhoods: round joins and caps. */
function strokeMask(lines, half, mask, g) {
  for (const { pts, closed } of lines) {
    const n = closed ? pts.length : pts.length - 1;
    for (let i = 0; i < n; i++) {
      const [ax, ay] = pts[i], [bx, by] = pts[(i + 1) % pts.length];
      const dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy;
      const x0 = Math.max(0, Math.floor(Math.min(ax, bx) - half - 1));
      const x1 = Math.min(g - 1, Math.ceil(Math.max(ax, bx) + half + 1));
      const y0 = Math.max(0, Math.floor(Math.min(ay, by) - half - 1));
      const y1 = Math.min(g - 1, Math.ceil(Math.max(ay, by) + half + 1));
      for (let row = y0; row <= y1; row++) {
        const py = row + 0.5;
        for (let col = x0; col <= x1; col++) {
          const px = col + 0.5;
          const t = len2 === 0 ? 0 : Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2));
          const qx = ax + t * dx - px, qy = ay + t * dy - py;
          if (qx * qx + qy * qy <= half * half) mask[row * g + col] = 1;
        }
      }
    }
  }
}

/** Paint the art, in order, over a transparent square; RGBA bytes. */
function rasterise(art, size, k) {
  const g = size * k;
  const [bx, by, bw, bh] = art.box;
  const scale = g / Math.max(bw, bh);
  const map = ([x, y]) => [(x - bx) * scale, (y - by) * scale];
  const rgba = new Float64Array(size * size * 4); // premultiplied
  const mask = new Uint8Array(g * g);
  const paint = (hex, alpha) => {
    const r = parseInt(hex.slice(0, 2), 16) / 255;
    const gr = parseInt(hex.slice(2, 4), 16) / 255;
    const b = parseInt(hex.slice(4, 6), 16) / 255;
    for (let py = 0; py < size; py++) {
      for (let px = 0; px < size; px++) {
        let hits = 0;
        for (let sy = 0; sy < k; sy++) {
          const base = (py * k + sy) * g + px * k;
          for (let sx = 0; sx < k; sx++) hits += mask[base + sx];
        }
        if (!hits) continue;
        const a = alpha * hits / (k * k);
        const i = (py * size + px) * 4;
        rgba[i] = r * a + rgba[i] * (1 - a);
        rgba[i + 1] = gr * a + rgba[i + 1] * (1 - a);
        rgba[i + 2] = b * a + rgba[i + 2] * (1 - a);
        rgba[i + 3] = a + rgba[i + 3] * (1 - a);
      }
    }
  };
  for (const l of art.layers) {
    const lines = polylines(l.ops, map);
    if (l.fill) {
      mask.fill(0);
      fillMask(lines, mask, g);
      paint(l.fill, l.fillOpacity);
    }
    if (l.stroke) {
      mask.fill(0);
      strokeMask(lines, l.strokeWidth * scale / 2, mask, g);
      paint(l.stroke, l.strokeOpacity);
    }
  }
  const out = Buffer.alloc(size * size * 4);
  for (let i = 0; i < size * size; i++) {
    const a = rgba[i * 4 + 3];
    for (let c = 0; c < 3; c++) out[i * 4 + c] = a > 0 ? Math.round(Math.min(1, rgba[i * 4 + c] / a) * 255) : 0;
    out[i * 4 + 3] = Math.round(Math.min(1, a) * 255);
  }
  return out;
}

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xFFFFFFFF;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xFF] ^ (c >>> 8);
  return (c ^ 0xFFFFFFFF) >>> 0;
}

/** A minimal RGBA PNG: IHDR, one IDAT, IEND. Deterministic byte for byte. */
function encodePng(rgba, size) {
  const zlib = require('zlib');
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([len, body, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0; // filter: none
    rgba.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

function sessionDonePng(win) {
  const pose = win.AQ.POSES.find((x) => x[0] === 'session_done');
  if (!pose) throw new Error('aq-icons.js: no session_done pose in AQ.POSES');
  const art = parseArt(win.AQ.adaPose(pose[2]), 'adaPose(session_done)');
  return encodePng(rasterise(art, PNG_SIZE, PNG_SUPERSAMPLE), PNG_SIZE);
}

