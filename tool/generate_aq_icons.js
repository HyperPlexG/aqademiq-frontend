#!/usr/bin/env node
/*
 * Aqademiq icon pack -> Dart.
 *
 *   node tool/generate_aq_icons.js                 generate + verify
 *   node tool/generate_aq_icons.js --sheet=x.html  also write a contact sheet
 *   node tool/generate_aq_icons.js --check         verify only, write nothing
 *
 * Source of truth (never edit the Dart by hand):
 *   prototypes/v11/aq-icons.js       window.AQ.ICONS   (geometry, roles, fill variants)
 *   prototypes/v11/aq-task-icons.js  window.AQT.TASKS  (Tier-2 two-layer task icons)
 *   prototypes/v11/app.jsx           AQ_MAP, AQ_ICE_GLYPHS, the derived aqx_ring glyph
 *
 * Output:
 *   lib/shared/icons/aq_icons.g.dart   AqIcons / AqTaskIcons (public API, a library)
 *   lib/shared/icons/aq_glyphs.g.dart  path data + glyph definitions (part of the above)
 *
 * Every SVG path is normalised to absolute M/L/C/Z (H/V -> L, S/Q/T -> C, arcs -> cubic
 * Beziers of at most 90 degrees via the SVG endpoint -> centre conversion) and then
 * verified against an independent sampler of the ORIGINAL path: the two-way distance
 * between the curves must stay under TOLERANCE grid units, or the run fails.
 *
 * Node built-ins only. No dependencies.
 */
