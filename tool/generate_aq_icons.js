const SVG_HEAD = (sw) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="100%" height="100%" style="display:block;overflow:visible" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round">`;

/** Renders the normalised model the way AqIcon paints it, with SVG masks for the roles. */
function renderModel(g, { fill = false, progress = null, uid, sw = DEFAULT_STROKE }) {
  const useFill = (fill && g.hasFill) || g.fillOnly;
  const D = (n) => opsToD(n.ops);
  const so = (l) => (l.opacity < 1 ? ` stroke-opacity="${l.opacity}" fill-opacity="${l.opacity}"` : '');
  const maskOpen = `<mask id="${uid}" maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24"><rect width="24" height="24" fill="white" stroke="none"/>`;
  if (!useFill) {
    const el = (l) => {
      const dash = l.timer && progress != null && progress < 1 ? ` pathLength="1" stroke-dasharray="${progress} 1"` : '';
      return `<path d="${D(l.norm)}"${l.paint ? ' fill="currentColor"' : ''}${so(l)}${dash}/>`;
    };
    const cuts = g.layers.filter((l) => l.role === 'cut');
    if (!cuts.length) return SVG_HEAD(sw) + g.layers.map(el).join('') + '</svg>';
    return SVG_HEAD(sw) + maskOpen + cuts.map((l) => `<path d="${D(l.norm)}" stroke="black" stroke-width="${sw + 3}"/>`).join('') + '</mask>' +
      `<g mask="url(#${uid})">` + g.layers.filter((l) => l.role !== 'cut').map(el).join('') + '</g>' + cuts.map(el).join('') + '</svg>';
  }
  const layers = g.fillLayers || g.layers;
  const knocks = layers.filter((l) => l.role === 'knock');
  const rest = layers.filter((l) => l.role !== 'knock');
  const el = (l) => `<path d="${D(l.norm)}"${l.role === 'body' || l.paint ? ' fill="currentColor"' : ''}${so(l)}/>`;
  if (!knocks.length) return SVG_HEAD(sw) + rest.map(el).join('') + '</svg>';
  return SVG_HEAD(sw) + maskOpen + knocks.map((l) => `<path d="${D(l.fdNorm || l.norm)}"${l.kfill ? ' fill="black" stroke="none"' : ` stroke="black" stroke-width="${l.sw == null ? sw : l.sw}"`}/>`).join('') + '</mask>' +
    `<g mask="url(#${uid})">` + rest.map(el).join('') + '</g></svg>';
}

