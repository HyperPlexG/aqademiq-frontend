/*
 * An independent reading of the ORIGINAL path: its own tokenizer, and each command
 * evaluated in its own terms (quadratics as quadratics, arcs by angle around a centre
 * derived from the spec's formulas written a second time, vector style).
 */
function originalCommands(d) {
  const tokens = d.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?/g) || [];
  const out = [];
  let k = 0;
  let cmd = null;
  let cur = [0, 0], start = [0, 0];
  let prevC2 = null, prevQ = null, closed = false;
  const take = () => parseFloat(tokens[k++]);
  const lerp = (a, b) => (t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
  while (k < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[k])) cmd = tokens[k++];
    else if (cmd === null || cmd === 'Z' || cmd === 'z') throw new Error('checker: number without command in ' + d);
    const rel = cmd === cmd.toLowerCase();
    const U = cmd.toUpperCase();
    const P = (x, y) => (rel ? [cur[0] + x, cur[1] + y] : [x, y]);
    let fn = null, end = cur, c2 = null, q = null;
    const from = cur;
    const restart = closed && U !== 'M' ? cur : null;
    closed = false;
    if (U === 'M') { end = P(take(), take()); start = end; fn = null; }
    else if (U === 'L') { end = P(take(), take()); fn = lerp(from, end); }
    else if (U === 'H') { const x = take(); end = [rel ? cur[0] + x : x, cur[1]]; fn = lerp(from, end); }
    else if (U === 'V') { const y = take(); end = [cur[0], rel ? cur[1] + y : y]; fn = lerp(from, end); }
    else if (U === 'C' || U === 'S') {
      const c1 = U === 'C' ? P(take(), take()) : prevC2 ? [2 * cur[0] - prevC2[0], 2 * cur[1] - prevC2[1]] : cur;
      c2 = P(take(), take());
      end = P(take(), take());
      const p0 = from, b = c1, c = c2, e = end;
      fn = (t) => { const u = 1 - t; return [0, 1].map((i) => u * u * u * p0[i] + 3 * u * u * t * b[i] + 3 * u * t * t * c[i] + t * t * t * e[i]); };
    } else if (U === 'Q' || U === 'T') {
      q = U === 'Q' ? P(take(), take()) : prevQ ? [2 * cur[0] - prevQ[0], 2 * cur[1] - prevQ[1]] : cur;
      end = P(take(), take());
      const p0 = from, b = q, e = end;
      fn = (t) => { const u = 1 - t; return [0, 1].map((i) => u * u * p0[i] + 2 * u * t * b[i] + t * t * e[i]); };
    } else if (U === 'A') {
      let rx = Math.abs(take()), ry = Math.abs(take());
      const phi = (take() * Math.PI) / 180;
      const large = take() !== 0, sweep = take() !== 0;
      end = P(take(), take());
      const p0 = from, p1 = end;
      if (p0[0] === p1[0] && p0[1] === p1[1]) fn = () => p0;
      else if (rx === 0 || ry === 0) fn = lerp(p0, p1);
      else {
        // Rotate the half-chord into the ellipse frame.
        const c = Math.cos(phi), s = Math.sin(phi);
        const h = [(p0[0] - p1[0]) / 2, (p0[1] - p1[1]) / 2];
        const hp = [c * h[0] + s * h[1], -s * h[0] + c * h[1]];
        const scale = Math.hypot(hp[0] / rx, hp[1] / ry);
        if (scale > 1) { rx *= scale; ry *= scale; }
        // In unit-circle space the chord midpoint m and the centre lie on its bisector.
        const u = [hp[0] / rx, hp[1] / ry];
        const half = Math.hypot(u[0], u[1]);
        const dist = Math.sqrt(Math.max(0, 1 - half * half));
        const nrm = [u[1] / half, -u[0] / half];
        const sign = large === sweep ? -1 : 1;
        const cu = [sign * dist * nrm[0], sign * dist * nrm[1]]; // centre, unit space, relative to midpoint
        const a0 = Math.atan2(u[1] - cu[1], u[0] - cu[0]);
        let a1 = Math.atan2(-u[1] - cu[1], -u[0] - cu[0]);
        let sweepAng = a1 - a0;
        while (sweep && sweepAng <= 0) sweepAng += 2 * Math.PI;
        while (!sweep && sweepAng >= 0) sweepAng -= 2 * Math.PI;
        const mid = [(p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2];
        fn = (t) => {
          const a = a0 + sweepAng * t;
          const ex = (cu[0] + Math.cos(a)) * rx, ey = (cu[1] + Math.sin(a)) * ry;
          return [mid[0] + c * ex - s * ey, mid[1] + s * ex + c * ey];
        };
      }
    } else if (U === 'Z') { end = start; fn = lerp(from, start); closed = true; }
    else throw new Error('checker: unknown command ' + cmd);
    out.push({ cmd, from, end, fn, restart });
    prevC2 = c2;
    prevQ = q;
    cur = end;
    if (U === 'M' && !/[a-zA-Z]/.test(tokens[k] || 'x')) cmd = rel ? 'l' : 'L';
  }
  return out;
}

function segDist(p, a, b) {
  const vx = b[0] - a[0], vy = b[1] - a[1];
  const l2 = vx * vx + vy * vy;
  let t = l2 ? ((p[0] - a[0]) * vx + (p[1] - a[1]) * vy) / l2 : 0;
  t = Math.max(0, Math.min(1, t));
  return Math.hypot(p[0] - a[0] - t * vx, p[1] - a[1] - t * vy);
}
function polyDist(p, poly) {
  if (poly.length === 1) return Math.hypot(p[0] - poly[0][0], p[1] - poly[0][1]);
  let m = Infinity;
  for (let i = 1; i < poly.length; i++) m = Math.min(m, segDist(p, poly[i - 1], poly[i]));
  return m;
}
const sample = (fn, n) => Array.from({ length: n + 1 }, (_, i) => fn(i / n));

/** Samples one group of normalised ops starting at `at` (with subpath start `st`). */
function normPolyline(ops, at, st, n) {
  const pts = [at];
  let cur = at, start = st;
  for (const o of ops) {
    if (o[0] === 'M') { cur = [o[1], o[2]]; start = cur; pts.length = 0; pts.push(cur); }
    else if (o[0] === 'L' || o[0] === 'Z') {
      const e = o[0] === 'L' ? [o[1], o[2]] : start;
      const a = cur;
      pts.push(...sample((t) => [a[0] + (e[0] - a[0]) * t, a[1] + (e[1] - a[1]) * t], n).slice(1));
      cur = e;
    } else {
      const a = cur, [x1, y1, x2, y2, x, y] = o.slice(1);
      pts.push(...sample((t) => { const u = 1 - t; return [u * u * u * a[0] + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * x, u * u * u * a[1] + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y]; }, n).slice(1));
      cur = [x, y];
    }
  }
  return { pts, cur, start };
}

/** Max two-way distance between the original path and its normalised form. */
function pathError(d, norm) {
  const orig = originalCommands(d);
  if (orig.length !== norm.groups.length) throw new Error(`checker: ${orig.length} vs ${norm.groups.length} commands in "${d}"`);
  let max = 0;
  let cur = [0, 0], start = [0, 0];
  for (let i = 0; i < orig.length; i++) {
    const o = orig[i];
    const g = norm.groups[i];
    const res = normPolyline(g.ops, cur, start, 96);
    let origPts;
    if (o.fn) origPts = sample(o.fn, 256);
    else origPts = [o.end]; // M: a point
    const coarse = o.fn ? sample(o.fn, 48) : origPts;
    for (const p of coarse) max = Math.max(max, polyDist(p, res.pts));
    for (const p of res.pts) max = Math.max(max, polyDist(p, origPts));
    // End points must agree too (catches a dropped or misplaced segment).
    max = Math.max(max, Math.hypot(res.cur[0] - o.end[0], res.cur[1] - o.end[1]));
    cur = res.cur;
    start = res.start;
  }
  return max;
}

/** Semantic spot checks that do not share code with either reading of the path. */
function spotChecks(model) {
  const fails = [];
  const byName = Object.fromEntries(model.glyphs.map((g) => [g.name, g]));
  const pts = (norm) => normPolyline(norm.ops, [0, 0], [0, 0], 64).pts;
  const near = (ps, q, tol = 0.01) => polyDist(q, ps) < tol;
  // 1. circ(12, 12, 9): a circle through all four extremes, radius 9 everywhere.
  const ring = pts(byName.check_circle.layers[0].norm);
  if (!ring.every((p) => Math.abs(Math.hypot(p[0] - 12, p[1] - 12) - 9) < 0.01)) fails.push('C9 is not a radius-9 circle');
  for (const q of [[21, 12], [3, 12], [12, 3], [12, 21]]) if (!near(ring, q)) fails.push(`C9 misses ${q}`);
  // 2. The squircle cube: bbox 3..21 and convex (an inverted corner arc would dent it). The source
  //    rounds its handles to 0.01 (r2), so the original itself reaches 2.99 / 21.01.
  const cube = pts(byName.ice_breakers.layers[0].norm);
  const xs = cube.map((p) => p[0]), ys = cube.map((p) => p[1]);
  const bb = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
  if (bb.some((v, i) => Math.abs(v - [3, 3, 21, 21][i]) > 0.015)) fails.push('cube bbox ' + bb.map((v) => v.toFixed(3)));
  let sign = 0, concave = 0;
  const poly = cube.filter((p, i) => i === 0 || Math.hypot(p[0] - cube[i - 1][0], p[1] - cube[i - 1][1]) > 1e-3);
  for (let i = 0; i < poly.length; i++) {
    const a = poly[i], b = poly[(i + 1) % poly.length], c = poly[(i + 2) % poly.length];
    const cr = (b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0]);
    if (Math.abs(cr) < 1e-6) continue;
    if (!sign) sign = Math.sign(cr);
    else if (Math.sign(cr) !== sign) concave++;
  }
  if (concave) fails.push(`cube has ${concave} concave turns`);
  if (sign !== 1) fails.push('cube does not run clockwise (the cube timer relies on it)');
  if (Math.hypot(cube[0][0] - 12, cube[0][1] - 3) > 1e-9) fails.push('cube does not start at top centre');
  // 3. history: large clockwise arc from 4.64,7.75 round to 3.5,12 (centre 12,12, r 8.5).
  const hist = pts(byName.history.layers[0].norm);
  for (const q of [[12, 3.5], [20.5, 12], [12, 20.5]]) if (!near(hist, q)) fails.push(`history arc misses ${q}`);
  return fails;
}

function verify(model) {
  const perIcon = [];
  let worst = 0;
  const all = [
    ...model.glyphs.map((g) => ({ name: g.name, layers: [...g.layers, ...(g.fillLayers || [])] })),
    ...model.tasks.map((t) => ({ name: 'task_' + t.name, layers: t.layers })),
  ];
  for (const item of all) {
    let e = 0;
    for (const l of item.layers) {
      e = Math.max(e, pathError(l.d, l.norm));
      if (l.fd) e = Math.max(e, pathError(l.fd, l.fdNorm));
    }
    perIcon.push([item.name, e]);
    worst = Math.max(worst, e);
  }
  return { perIcon, worst, spot: spotChecks(model) };
}

