function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes('--check');
  const sheetArg = args.find((a) => a.startsWith('--sheet='));
  const src = loadSources();
  const model = buildModel(src);
  const result = verify(model);

  const top = [...result.perIcon].sort((a, b) => b[1] - a[1]).slice(0, 8);
  console.log(`glyphs: ${model.glyphs.length} outline, ${model.glyphs.filter((g) => g.hasFill).length} fill, ${model.tasks.length} task`);
  console.log(`AQ_MAP: ${model.materialToAq.length} mapped, ${model.gaps.length} gaps; ice: ${model.ice.join(', ')}`);
  console.log(`normalisation max error: ${result.worst.toExponential(3)} (tolerance ${TOLERANCE})`);
  console.log('worst icons: ' + top.map(([n, e]) => `${n} ${e.toExponential(2)}`).join(', '));

  const bad = result.perIcon.filter(([, e]) => !(e <= TOLERANCE));
  if (bad.length || result.spot.length) {
    for (const [n, e] of bad) console.error(`FAIL ${n}: error ${e}`);
    for (const f of result.spot) console.error('FAIL spot check: ' + f);
    process.exit(1);
  }
  console.log('spot checks: ok');

  if (sheetArg) {
    const file = path.resolve(sheetArg.slice('--sheet='.length));
    writeSheet(file, src, model, result);
    console.log('contact sheet: ' + file);
  }
  if (checkOnly) return;

  const { glyphsFile, iconsFile, uniquePaths } = emitDart(model);
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'aq_glyphs.g.dart'), glyphsFile);
  fs.writeFileSync(path.join(OUT, 'aq_icons.g.dart'), iconsFile);
  console.log(`wrote lib/shared/icons/aq_glyphs.g.dart (${(glyphsFile.length / 1024).toFixed(1)} KB, ${uniquePaths} unique paths)`);
  console.log(`wrote lib/shared/icons/aq_icons.g.dart (${(iconsFile.length / 1024).toFixed(1)} KB)`);
}

