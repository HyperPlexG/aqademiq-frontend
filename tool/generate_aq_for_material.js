#!/usr/bin/env node
// Maps every Material `Icons.x` the app uses to its Aqademiq glyph name, so
// `AppIcon` (lib/shared/icons/app_icon.dart) can draw the v11 icon pack in
// place of `Icon` everywhere without each call site knowing the aq names.
//
//   node tool/generate_aq_for_material.js        # writes lib/shared/icons/aq_for_material.g.dart
//   node tool/generate_aq_for_material.js --check
//
// A Material name resolves the way the prototype's `Ic` does: AQ_MAP first
// (materialToAq in aq_icons.g.dart), then an aq glyph of the same name. The
// `_outlined` / `_rounded` / `_sharp` / `_outline` / `_none` variants of a name
// resolve like the bare name, since the pack has one weight. Anything left over
// keeps its Material glyph (listed in the output so gaps are visible).

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'lib/shared/icons/aq_for_material.g.dart');
const ICONS = path.join(root, 'lib/shared/icons/aq_icons.g.dart');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.dart')) out.push(p);
  }
  return out;
}

const gen = fs.readFileSync(ICONS, 'utf8');
const section = (start) => {
  const i = gen.indexOf(start);
  if (i < 0) throw new Error(`missing ${start} in aq_icons.g.dart`);
  return gen.slice(i, gen.indexOf('};', i));
};
const pairs = (src) => [...src.matchAll(/'([^']+)':\s*'([^']+)'/g)].map((m) => [m[1], m[2]]);
const materialToAq = new Map(pairs(section('static const Map<String, String> materialToAq')));
const aqNames = new Set([...section('static const Map<String, AqGlyph> byName').matchAll(/'([^']+)':/g)].map((m) => m[1]));
const gapsSrc = gen.indexOf('materialGaps') >= 0 ? section('materialGaps') : '';
const gaps = new Set([...gapsSrc.matchAll(/'([^']+)'/g)].map((m) => m[1]));

const used = new Set();
for (const f of walk(path.join(root, 'lib'))) {
  if (f.includes(`${path.sep}icons${path.sep}`)) continue;
  for (const m of fs.readFileSync(f, 'utf8').matchAll(/(?<![A-Za-z0-9_])Icons\.([a-z0-9_]+)(?![A-Za-z0-9_])/g)) used.add(m[1]);
}

const SUFFIXES = ['_outlined', '_rounded', '_sharp'];
function resolve(name) {
  const tries = [name];
  for (const s of SUFFIXES) if (name.endsWith(s)) tries.push(name.slice(0, -s.length));
  for (const t of [...tries]) {
    if (t.endsWith('_outline')) tries.push(t.slice(0, -'_outline'.length));
    if (t.endsWith('_none')) tries.push(t.slice(0, -'_none'.length));
  }
  for (const t of tries) {
    if (gaps.has(t)) return null;
    const mapped = materialToAq.get(t);
    if (mapped) return mapped;
    if (aqNames.has(t)) return t;
  }
  return null;
}

const mapped = [];
const left = [];
for (const name of [...used].sort()) {
  const aq = resolve(name);
  if (aq) mapped.push([name, aq]);
  else left.push(name);
}

const out = `// GENERATED by tool/generate_aq_for_material.js — do not edit.
// Every Material icon used in lib/ that the Aqademiq pack draws, by its aq
// name. Kept Material (no glyph in the pack): ${left.length ? left.join(', ') : 'none'}.

part of 'app_icon.dart';

final Map<IconData, String> _aqForMaterial = <IconData, String>{
${mapped.map(([m, aq]) => `  Icons.${m}: '${aq}',`).join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== out) {
    console.error('out of date: run node tool/generate_aq_for_material.js');
    process.exit(1);
  }
  console.log('up to date');
} else {
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(root, OUT)}: ${mapped.length} mapped, ${left.length} kept Material`);
  console.log('kept Material:', left.join(' '));
}
