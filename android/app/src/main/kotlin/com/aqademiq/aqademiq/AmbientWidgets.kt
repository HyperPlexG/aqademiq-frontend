/**
 * The three home-screen widgets (v11 wg-home), the Android half of the iOS ones
 * in `ios/AmbientWidgets/AmbientWidgets.swift`: Next, This week, Focus.
 *
 * Like the iOS extension, they never think. The app derives everything they
 * show and [AmbientBridge] keeps it as one small JSON object in shared prefs;
 * a widget reads that object and draws it. No network, no models, no work —
 * which is also why they are correct with the app closed.
 *
 * In v11 they follow the theme (every colour a resource with a values-night
 * twin) and draw the icon pack: aq_brand_ada on Focus, the session cube while
 * a session runs, and Ada at the mood logged each day on This week.
 *
 * They are redrawn whenever the app publishes or a session starts, changes or
 * ends ([refresh]), and every 30 minutes besides, which is what moves "today"
 * across midnight on This week.
 */
object AmbientWidgets {

    /** Redraw every widget the student has placed, from the latest state. */
    fun refresh(context: Context) {
        val manager = AppWidgetManager.getInstance(context)
        val glance = Glance.load(context)
        for (widget in listOf(NextWidget(), WeekWidget(), FocusWidget())) {
            val ids = manager.getAppWidgetIds(ComponentName(context, widget.javaClass))
            if (ids.isNotEmpty()) manager.updateAppWidget(ids, widget.draw(context, glance))
        }
    }

    /**
     * A tap, as intent rather than as a route: `aqademiq://plan` means "show
     * the plan", and the app decides where that is. Renaming a route cannot
     * break a widget already sitting on someone's home screen.
     */
    internal fun open(context: Context, intent: String): PendingIntent =
        PendingIntent.getActivity(
            context,
            intent.hashCode(),
            Intent(Intent.ACTION_VIEW, Uri.parse("aqademiq://$intent"), context, MainActivity::class.java)
                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP),
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
        )

    /** Levels in ambient_cube.xml, generated by tool/generate_ambient_glyphs.js. */
    internal const val CUBE_LEVELS = 20
}

/** What the widgets show, read once from the state the app published. */
internal class Glance(
    val nextTitle: String?,
    val nextTime: String?,
    val nextSubject: String?,
    val nextTint: Int?,
    /**
     * Seven entries, Monday first: the mood logged that day, 0 Rough … 4
     * Great, or null for a day with no check-in.
     */
    val weekMoods: List<Int?>,
    /** The running session, or null when there is none. */
    val session: SessionGlance?,
) {
    companion object {
        fun load(context: Context): Glance {
            val json = AmbientBridge.state(context)
            return Glance(
                nextTitle = json.text("nextTaskTitle"),
                nextTime = json.text("nextTaskTime"),
                nextSubject = json.text("nextTaskSubject"),
                nextTint = json.text("nextTaskTint")?.let(::parseHex),
                weekMoods = weekMoods(json),
                session = json.optJSONObject("session")?.let { SessionGlance.from(it) },
            )
        }

        /**
         * The week's moods. A payload from before `weekMoods` existed still
         * says which days were shown up for; those wear Ada at her best rather
         * than going blank.
         *
         * Only if the payload is this week's (`weekOf`, its Monday): it is
         * rewritten only when the app publishes, so after Monday's rollover
         * it still holds last week's moods, and those are not this week's.
         * Every day is then an empty outline until the app says otherwise.
         */
        private fun weekMoods(json: JSONObject): List<Int?> {
            if (json.text("weekOf") != thisMonday()) return List(7) { null }
            val moods = json.optJSONArray("weekMoods")
            val days = json.optJSONArray("weekDays")
            return List(7) { index ->
                if (moods != null && moods.length() > 0) {
                    // -1 is a day with no check-in (the payload carries no nulls).
                    moods.optInt(index, -1).takeIf { it in 0..4 }
                } else {
                    if (days?.optBoolean(index, false) == true) 4 else null
                }
            }
        }

        /**
         * This week's Monday as `yyyy-MM-dd`, local — the app's
         * `ambientDay(AppDate.mondayOf(now))`. java.time (desugared below 26)
         * rather than Calendar, which is not Gregorian in every locale.
         */
        private fun thisMonday(): String =
            java.time.LocalDate.now()
                .with(java.time.temporal.TemporalAdjusters.previousOrSame(java.time.DayOfWeek.MONDAY))
                .toString()

        private fun JSONObject.text(key: String): String? =
            if (isNull(key)) null else optString(key).takeIf { it.isNotBlank() }

        /** `#RRGGBB` as the app writes it. */
        private fun parseHex(raw: String): Int? = try {
            Color.parseColor(if (raw.startsWith("#")) raw else "#$raw")
        } catch (e: IllegalArgumentException) {
            null
        }
    }
}

/** A running session, as the Focus widget draws it. */
internal class SessionGlance(
    val frozen: Boolean,
    /** The session cube's trim: time left in [AmbientWidgets.CUBE_LEVELS] steps. */
    val cubeLevel: Int,
) {
    companion object {
        fun from(json: JSONObject): SessionGlance {
            val frozen = json.optBoolean("frozen", false)
            val duration = json.optInt("durationSec", 0)
            val endsAt = AmbientBridge.parseInstant(json.optString("endsAt", ""))
            // Read as the widget is drawn — on a publish, never per second.
            val left = if (frozen || endsAt <= 0L) {
                json.optInt("remainingSec", 0)
            } else {
                ((endsAt - System.currentTimeMillis()) / 1000L).toInt()
            }
            val level = if (duration <= 0) {
                AmbientWidgets.CUBE_LEVELS
            } else {
                (left.coerceIn(0, duration).toFloat() / duration * AmbientWidgets.CUBE_LEVELS)
                    .roundToInt()
                    .coerceIn(0, AmbientWidgets.CUBE_LEVELS)
            }
            return SessionGlance(frozen = frozen, cubeLevel = level)
        }
    }
}

/** A widget that draws itself from a [Glance]; the system calls in on its schedule. */
abstract class AmbientWidget : AppWidgetProvider() {
    internal abstract fun draw(context: Context, glance: Glance): RemoteViews

    override fun onUpdate(context: Context, manager: AppWidgetManager, ids: IntArray) {
        manager.updateAppWidget(ids, draw(context, Glance.load(context)))
    }
}

/** One task, not three, not a list. */
class NextWidget : AmbientWidget() {
    override fun draw(context: Context, glance: Glance): RemoteViews {
        val views = RemoteViews(context.packageName, R.layout.widget_next)
        val title = glance.nextTitle
        if (title == null) {
            views.setViewVisibility(R.id.next_title, View.GONE)
            views.setViewVisibility(R.id.next_meta, View.GONE)
            views.setViewVisibility(R.id.next_empty, View.VISIBLE)
        } else {
            views.setViewVisibility(R.id.next_empty, View.GONE)
            views.setViewVisibility(R.id.next_title, View.VISIBLE)
            views.setTextViewText(R.id.next_title, title)
            // "2:00 PM · CN 302": the time, then the class.
            val meta = listOfNotNull(glance.nextTime, glance.nextSubject)
                .joinToString(" · ")
                .takeIf { it.isNotEmpty() }
            views.setViewVisibility(R.id.next_meta, if (meta == null) View.GONE else View.VISIBLE)
            views.setTextViewText(R.id.next_time, meta ?: "")
            // The class's own colour; the accent when it has none.
            views.setInt(
                R.id.next_dot,
                "setColorFilter",
                glance.nextTint ?: context.getColor(R.color.widget_accent),
            )
        }
        views.setOnClickPendingIntent(android.R.id.background, AmbientWidgets.open(context, "plan"))
        return views
    }
}

/** Seven marks, and no judgement. */
class WeekWidget : AmbientWidget() {
    override fun draw(context: Context, glance: Glance): RemoteViews {
        val views = RemoteViews(context.packageName, R.layout.widget_week)
        // Monday-first index of today, matching AppDate.mondayOf in the app.
        val today = (Calendar.getInstance().get(Calendar.DAY_OF_WEEK) + 5) % 7
        for (index in 0 until 7) {
            val mood = glance.weekMoods[index]
            val isToday = index == today
            views.setImageViewResource(
                DAYS[index],
                when {
                    // A day checked in wears Ada at the mood logged.
                    mood != null -> MOODS[mood]
                    // Still open, nothing lost: the outline in the accent.
                    isToday -> R.drawable.widget_day_today
                    // Absence is an empty outline, never a puddle.
                    else -> R.drawable.widget_day_empty
                },
            )
            views.setViewVisibility(PLUS[index], if (mood == null && isToday) View.VISIBLE else View.GONE)
            // Today's letter is the only accent. Every letter is set, because
            // the layout's own defaults are the gallery's sample week.
            views.setTextColor(
                LETTER_VIEWS[index],
                context.getColor(if (isToday) R.color.widget_accent else R.color.widget_dim),
            )
        }
        views.setOnClickPendingIntent(android.R.id.background, AmbientWidgets.open(context, "stats"))
        return views
    }

    private companion object {
        val MOODS = intArrayOf(
            R.drawable.aq_ada_mood_0, R.drawable.aq_ada_mood_1, R.drawable.aq_ada_mood_2,
            R.drawable.aq_ada_mood_3, R.drawable.aq_ada_mood_4,
        )
        val DAYS = intArrayOf(
            R.id.week_day_0, R.id.week_day_1, R.id.week_day_2, R.id.week_day_3,
            R.id.week_day_4, R.id.week_day_5, R.id.week_day_6,
        )
        val PLUS = intArrayOf(
            R.id.week_plus_0, R.id.week_plus_1, R.id.week_plus_2, R.id.week_plus_3,
            R.id.week_plus_4, R.id.week_plus_5, R.id.week_plus_6,
        )
        val LETTER_VIEWS = intArrayOf(
            R.id.week_letter_0, R.id.week_letter_1, R.id.week_letter_2, R.id.week_letter_3,
            R.id.week_letter_4, R.id.week_letter_5, R.id.week_letter_6,
        )
    }
}

/** Start 5 min: the one operable thing on any widget. */
class FocusWidget : AmbientWidget() {
    override fun draw(context: Context, glance: Glance): RemoteViews {
        val views = RemoteViews(context.packageName, R.layout.widget_focus)
        val session = glance.session
        if (session == null) {
            views.setImageViewResource(R.id.focus_ada, R.drawable.aq_brand_ada)
            views.setViewVisibility(R.id.focus_status, View.GONE)
            views.setViewVisibility(R.id.focus_status_frozen, View.GONE)
            views.setViewVisibility(R.id.focus_button, View.VISIBLE)
        } else {
            // A session is already running: show its cube and say so, rather
            // than offering to start a second one.
            views.setImageViewResource(R.id.focus_ada, R.drawable.ambient_cube)
            views.setInt(R.id.focus_ada, "setImageLevel", session.cubeLevel)
            views.setViewVisibility(R.id.focus_button, View.GONE)
            views.setViewVisibility(R.id.focus_status, if (session.frozen) View.GONE else View.VISIBLE)
            views.setViewVisibility(R.id.focus_status_frozen, if (session.frozen) View.VISIBLE else View.GONE)
        }
        // Mid-session the app already refuses to start a second one, so the
        // same tap simply opens the running session — as on iOS.
        val start = AmbientWidgets.open(context, "focus/start5")
        views.setOnClickPendingIntent(android.R.id.background, start)
        views.setOnClickPendingIntent(R.id.focus_button, start)
        return views
    }
}
